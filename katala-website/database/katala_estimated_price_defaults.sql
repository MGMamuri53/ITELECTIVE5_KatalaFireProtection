SET
  v_minprice = CASE v_servicecode
    WHEN 'SYS-INSTALL' THEN 15000
    WHEN 'SYS-MAINT' THEN 2500
    ELSE v_minprice
  END,
  v_maxprice = CASE v_servicecode
    WHEN 'SYS-INSTALL' THEN 80000
    WHEN 'SYS-MAINT' THEN 15000
    ELSE v_maxprice
  END
WHERE v_servicecode IN ('SYS-INSTALL', 'SYS-MAINT');
