-- Katala Supabase full reset.
-- Destructive: drops every base table in public, then recreates the app-compatible schema.
-- Supabase Auth users are not dropped. Admin/staff profiles are attached if those Auth users exist.

BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

DROP VIEW IF EXISTS public.vw_user_roles CASCADE;

DO $$
DECLARE
  table_record record;
BEGIN
  FOR table_record IN
    SELECT tablename
    FROM pg_tables
    WHERE schemaname = 'public'
  LOOP
    EXECUTE format('DROP TABLE IF EXISTS public.%I CASCADE', table_record.tablename);
  END LOOP;
END $$;

